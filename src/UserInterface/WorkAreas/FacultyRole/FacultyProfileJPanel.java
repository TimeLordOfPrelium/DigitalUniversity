    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String firstname = txtFirstName.getText().trim();
        String lastname = txtLastName.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhone.getText().trim();
        String title = txtFacultyTitle.getText().trim();
        String office = txtOffice.getText().trim();
        String officehours = txtOfficeHours.getText().trim();
        String researcharea = txtResearchArea.getText().trim();

        if (!FacultyInputRules.isValidName(firstname) || !FacultyInputRules.isValidName(lastname)) {
            showError("First and last name are required and may only contain letters, spaces, hyphens and apostrophes.");
            return;
        }
        if (!FacultyInputRules.isValidEmail(email)) {
            showError("Please enter a valid email address, e.g. name@northeastern.edu.");
            return;
        }
        //email must stay unique across the university
        Person owner = business.getPersonDirectory().findPersonByEmail(email);
        if (owner != null && owner != faculty.getPerson()) {
            showError("That email address already belongs to someone else.");
            return;
        }
        if (!FacultyInputRules.isValidPhone(phone)) {
            showError("Phone number must have 10 digits, e.g. 617-555-0123 (or leave it empty).");
            return;
        }
        if (FacultyInputRules.isBlank(title)) {
            showError("Title is required, e.g. Associate Professor.");
            return;
        }
        if (!FacultyInputRules.isWithinLength(title, 50) || !FacultyInputRules.isWithinLength(office, 50)
                || !FacultyInputRules.isWithinLength(officehours, 50) || !FacultyInputRules.isWithinLength(researcharea, 50)) {
            showError("Title, office, office hours and research area must be 50 characters or less.");
            return;
        }

        Person person = faculty.getPerson();
        person.setFirstName(firstname);
        person.setLastName(lastname);
        person.setEmail(email);
        person.setPhone(phone);
        faculty.setTitle(title);
        faculty.setOffice(office);
        faculty.setOfficeHours(officehours);
        faculty.setResearchArea(researcharea);

        displayProfile();
        setEditing(false);
        JOptionPane.showMessageDialog(this, "Your profile has been updated.", "My Profile", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnSaveActionPerformed

