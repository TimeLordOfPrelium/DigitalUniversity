    private void displayStudent() {
        Person person = student.getPerson();
        lblName.setText(person.getFullName());
        txtStudentId.setText(person.getPersonId());
        txtEmail.setText(person.getEmail());
        txtPhone.setText(FacultyInputRules.isBlank(person.getPhone()) ? "Not provided" : person.getPhone());
        txtHobbies.setText(FacultyInputRules.isBlank(student.getHobbies()) ? "Not provided" : student.getHobbies());
        txtInterests.setText(FacultyInputRules.isBlank(student.getInterests()) ? "Not provided" : student.getInterests());

        Transcript transcript = student.getAcademicProfile().getTranscript();
        Degree degree = business.getDepartment().getDegree();
        ArrayList<SeatAssignment> completed = StudentProgress.getCompletedClasses(transcript);
        int completedcredits = StudentProgress.getCompletedCredits(transcript);

        float gpa = transcript.getGPA();
        txtGpa.setText(gpa > 0 ? String.format("%.2f (%s)", gpa, GradeScale.toLetter(gpa)) : "No grades yet");
        txtCompleted.setText(String.valueOf(completedcredits));
        txtInProgress.setText(String.valueOf(transcript.getTotalCreditHours() - completedcredits));
        txtCore.setText(degree.validateCoreClasses(completed) ? "Yes, all core done" : "Not yet");
        txtElectives.setText(String.valueOf(degree.getTotalElectiveCoursesTaken(completed)));
        txtDegree.setText(completedcredits + " of " + StudentProgress.CREDITS_TO_GRADUATE + " credits");

        DefaultTableModel model = (DefaultTableModel) tblCourses.getModel();
        model.setRowCount(0);
        for (SeatAssignment sa : StudentProgress.getClassesBySemester(transcript)) {
            Object[] row = new Object[4];
            row[0] = sa.getCourseLoad().getSemester();
            row[1] = sa.getCourseOffer().toString();
            row[2] = sa.getCreditHours();
            row[3] = GradeScale.isGraded(sa.getGrade()) ? GradeScale.toLetter(sa.getGrade()) : "In progress";
            model.addRow(row);
        }
    }

