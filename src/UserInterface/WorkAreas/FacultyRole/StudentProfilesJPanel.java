    private void btnViewProfileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewProfileActionPerformed
        int selectedrow = tblStudents.getSelectedRow();
        if (selectedrow < 0 || selectedrow >= rowstudents.size()) {
            JOptionPane.showMessageDialog(this, "Please select a student first.", "No selection", JOptionPane.WARNING_MESSAGE);
            return;
        }
        StudentProfile sp = rowstudents.get(selectedrow);
        //double check: faculty may only open profiles of their own students
        if (!TeachingRoster.teaches(business, faculty, sp)) {
            JOptionPane.showMessageDialog(this, "You can only view students enrolled in your classes.",
                    "Access denied", JOptionPane.ERROR_MESSAGE);
            return;
        }
        CardSequencePanel.add(new StudentProfileDetailJPanel(business, sp, CardSequencePanel));
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);
    }//GEN-LAST:event_btnViewProfileActionPerformed

