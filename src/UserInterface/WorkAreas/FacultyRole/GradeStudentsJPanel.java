    private void btnAssignGradeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAssignGradeActionPerformed
        if (!cangrade) {
            return;
        }
        SeatAssignment sa = getSelectedSeat();
        if (sa == null) {
            return;
        }
        Object letter = cmbGrade.getSelectedItem();
        float points = GradeScale.toPoints(letter == null ? null : letter.toString());
        if (points < 0) {
            JOptionPane.showMessageDialog(this, "Please pick a letter grade.", "Invalid grade", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int selectedrow = tblStudents.getSelectedRow();
        sa.setGrade(points);
        refreshTable();
        tblStudents.setRowSelectionInterval(selectedrow, selectedrow); //keep the same student selected
    }//GEN-LAST:event_btnAssignGradeActionPerformed

    private void btnClearGradeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnClearGradeActionPerformed
        if (!cangrade) {
            return;
        }
        SeatAssignment sa = getSelectedSeat();
        if (sa == null) {
            return;
        }
        int choice = JOptionPane.showConfirmDialog(this, "Clear this student's grade? The class will show as not graded.",
                "Clear grade", JOptionPane.YES_NO_OPTION);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        int selectedrow = tblStudents.getSelectedRow();
        sa.setGrade(0); //0 means not graded
        refreshTable();
        tblStudents.setRowSelectionInterval(selectedrow, selectedrow); //keep the same student selected
    }//GEN-LAST:event_btnClearGradeActionPerformed

