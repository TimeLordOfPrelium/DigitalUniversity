    public GradeStudentsJPanel(Business b, CourseOffer co, JPanel clp) {
        business = b;
        courseoffer = co;
        CardSequencePanel = clp;
        rowseats = new ArrayList<>();
        initComponents();
        tblStudents.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

        for (String letter : GradeScale.LETTERS) {
            cmbGrade.addItem(letter);
        }
        lblCourse.setText(courseoffer + "  -  " + TeachingRoster.getSemester(business, courseoffer));

        cangrade = TeachingRoster.isCurrentSemester(business, courseoffer);
        if (cangrade) {
            lblStatus.setText("Select a student, pick a letter grade and click Assign Grade.");
        } else {
            lblStatus.setText(TeachingRoster.getSemester(business, courseoffer) + " is closed, so grades are read-only.");
        }
        cmbGrade.setEnabled(cangrade);
        btnAssignGrade.setEnabled(cangrade);
        btnClearGrade.setEnabled(cangrade);
        refreshTable();
    }

    public void refreshTable() {
        DefaultTableModel model = (DefaultTableModel) tblStudents.getModel();
        model.setRowCount(0);
        rowseats.clear();

        for (SeatAssignment sa : TeachingRoster.getEnrolledSeats(courseoffer)) {
            StudentProfile sp = TeachingRoster.findStudent(business, sa);
            if (sp == null) {
                continue; //seat not linked to a registered student
            }
            Object[] row = new Object[5];
            row[0] = sp.getPerson().getFullName();
            row[1] = sp.getPerson().getPersonId();
            row[2] = sp.getPerson().getEmail();
            row[3] = GradeScale.toLetter(sa.getGrade());
            row[4] = GradeScale.isGraded(sa.getGrade()) ? String.format("%.1f", sa.getGrade()) : "-";
            model.addRow(row);
            rowseats.add(sa);
        }
    }

    //the seat assignment in the selected row, or null (after telling the user) when nothing is selected
    private SeatAssignment getSelectedSeat() {
        int selectedrow = tblStudents.getSelectedRow();
        if (selectedrow < 0 || selectedrow >= rowseats.size()) {
            JOptionPane.showMessageDialog(this, "Please select a student first.", "No selection", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        return rowseats.get(selectedrow);
    }

