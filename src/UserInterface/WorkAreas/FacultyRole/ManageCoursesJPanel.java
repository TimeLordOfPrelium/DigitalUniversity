    static final String ALL_SEMESTERS = "All semesters";

    public ManageCoursesJPanel(Business b, UserAccount ua, JPanel clp) {
        business = b;
        useraccount = ua;
        faculty = (FacultyProfile) ua.getAssociatedPersonProfile();
        CardSequencePanel = clp;
        initComponents();
        tblCourses.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblCourses.getColumnModel().getColumn(0).setPreferredWidth(260); //room for the full course name
        tblCourses.getColumnModel().getColumn(1).setPreferredWidth(50);
        lblSubtitle.setText("The classes you teach. Only the current semester (" + business.getCurrentSemester()
                + ") can be updated or graded.");
        populateSemesters();
        refreshTable();

        //screens opened from here remove themselves on Back; reload so their changes show up
        addComponentListener(new java.awt.event.ComponentAdapter() {
            @Override
            public void componentShown(java.awt.event.ComponentEvent e) {
                refreshTable();
            }
        });
    }

    //semesters this faculty member taught in; the current semester is selected by default
    private void populateSemesters() {
        loading = true;
        cmbSemester.removeAllItems();
        cmbSemester.addItem(ALL_SEMESTERS);
        for (String semester : TeachingRoster.getSemesters(business, faculty)) {
            cmbSemester.addItem(semester);
        }
        if (business.getCurrentSemester() != null) {
            cmbSemester.setSelectedItem(business.getCurrentSemester());
        }
        loading = false;
    }

    public void refreshTable() {
        DefaultTableModel model = (DefaultTableModel) tblCourses.getModel();
        model.setRowCount(0);

        Object selected = cmbSemester.getSelectedItem();
        String semester = (selected == null || ALL_SEMESTERS.equals(selected)) ? null : selected.toString();

        for (CourseOffer co : TeachingRoster.getCourseOffers(business, faculty, semester)) {
            Object[] row = new Object[6];
            row[0] = co; //the course offer itself, so a selected row gives the offer back
            row[1] = co.getCreditHours();
            row[2] = TeachingRoster.getSemester(business, co);
            row[3] = co.getRoom();
            row[4] = co.getMeetingTime();
            row[5] = co.getEnrolledCount() + " / " + co.getCapacity();
            model.addRow(row);
        }
    }

    //the class in the selected row, or null (after telling the user) when nothing is selected
    private CourseOffer getSelectedCourseOffer() {
        int selectedrow = tblCourses.getSelectedRow();
        if (selectedrow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a course first.", "No selection", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        return (CourseOffer) tblCourses.getValueAt(selectedrow, 0);
    }

    private void openScreen(JPanel screen) {
        CardSequencePanel.add(screen);
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);
    }

