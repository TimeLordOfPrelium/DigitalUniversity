    private void SaveDetailsButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveDetailsButtonActionPerformed
        String first = FirstNameField.getText().trim();
        String last = LastNameField.getText().trim();
        String email = EmailField.getText().trim();
        String phone = PhoneField.getText().trim();

        Person person = useraccount.getAssociatedPersonProfile().getPerson();
        //you may keep your own email, so you are passed as the exception
        String error = PersonRules.validate(business.getPersonDirectory(), first, last, email, phone, person);
        if (error != null) {
            JOptionPane.showMessageDialog(this, error, "My Profile", JOptionPane.ERROR_MESSAGE);
            return;
        }

        person.setFirstName(first);
        person.setLastName(last);
        person.setEmail(email);
        person.setPhone(phone);

        JOptionPane.showMessageDialog(this, "Your details were saved.", "My Profile", JOptionPane.INFORMATION_MESSAGE);

    }//GEN-LAST:event_SaveDetailsButtonActionPerformed

    private void ChangePasswordButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ChangePasswordButtonActionPerformed
        String current = new String(CurrentPasswordField.getPassword());
        String newpw = new String(NewPasswordField.getPassword());
        String confirm = new String(ConfirmPasswordField.getPassword());

        //the current password proves it is really you, not someone at an unattended screen
        if (!useraccount.isPasswordCorrect(current)) {
            JOptionPane.showMessageDialog(this, "Your current password is incorrect.", "Change Password", JOptionPane.ERROR_MESSAGE);
            clearPasswordFields();
            return;
        }
        String error = AccountRules.validatePassword(newpw, confirm);
        if (error == null && newpw.equals(current)) {
            error = "The new password must be different from your current one.";
        }
        if (error != null) {
            JOptionPane.showMessageDialog(this, error, "Change Password", JOptionPane.ERROR_MESSAGE);
            return;
        }

        useraccount.setPassword(newpw);
        clearPasswordFields();
        JOptionPane.showMessageDialog(this, "Your password was changed. Use it the next time you log in.",
                "Change Password", JOptionPane.INFORMATION_MESSAGE);

    }//GEN-LAST:event_ChangePasswordButtonActionPerformed


