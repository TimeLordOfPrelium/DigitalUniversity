    private void CreateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CreateButtonActionPerformed
        Profile profile = (Profile) ProfileComboBox.getSelectedItem();
        if (profile == null) {
            JOptionPane.showMessageDialog(this, "Please choose a person.", "Create account", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String un = UsernameField.getText().trim();
        String pw = new String(PasswordField.getPassword());
        String confirm = new String(ConfirmField.getPassword());

        UserAccountDirectory uad = business.getUserAccountDirectory();
        String error = AccountRules.validateUsername(uad, un, null);
        if (error == null) {
            error = AccountRules.validatePassword(pw, confirm);
        }
        if (error != null) {
            JOptionPane.showMessageDialog(this, error, "Create account", JOptionPane.ERROR_MESSAGE);
            return;
        }

        uad.newUserAccount(profile, un, pw);
        JOptionPane.showMessageDialog(this, "Account \"" + un + "\" created for " + profile + ".",
                "Create account", JOptionPane.INFORMATION_MESSAGE);
        goBack();
    }//GEN-LAST:event_CreateButtonActionPerformed


