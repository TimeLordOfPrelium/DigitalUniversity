    //only people without a login are offered, so a person never gets two accounts for one role
    void loadProfiles() {

        ProfileComboBox.removeAllItems();
        for (Profile p : business.getProfilesWithoutAccount()) {
            ProfileComboBox.addItem(p);
        }

        if (ProfileComboBox.getItemCount() == 0) {
            HintLabel.setText("Everyone registered already has an account. Register a person first.");
            CreateButton.setEnabled(false);
        }
    }

