    void refresh() {

        String current = business.getCurrentSemester();
        CurrentValue.setText(current == null ? "Not set" : current);

        DefaultTableModel model = (DefaultTableModel) SemesterTable.getModel();
        model.setRowCount(0);

        ArrayList<CourseSchedule> schedules = new ArrayList<>(business.getDepartment().getCourseSchedules());
        schedules.sort(Comparator.comparing(cs -> sortKey(cs.getSemester())));

        for (CourseSchedule cs : schedules) {

            int enrolled = 0;
            for (CourseOffer co : cs.getSchedule()) {
                enrolled = enrolled + co.getEnrolledCount();
            }

            Object[] row = new Object[4];
            row[0] = cs.getSemester();
            row[1] = cs.getSchedule().size();
            row[2] = enrolled;
            row[3] = cs.getSemester().equals(current) ? "Current" : "";
            model.addRow(row);
        }
    }

    //orders "Spring2026" < "Summer2026" < "Fall2026" < "Spring2027"; unknown names sort by text
    static String sortKey(String semester) {

        String year = semester.replaceAll("\\D", "");
        String term = semester.replaceAll("\\d", "").toLowerCase();
        int order;
        switch (term) {
            case "spring":
                order = 1;
                break;
            case "summer":
                order = 2;
                break;
            case "fall":
                order = 3;
                break;
            default:
                order = 9;
        }
        return year + order + semester;
    }

