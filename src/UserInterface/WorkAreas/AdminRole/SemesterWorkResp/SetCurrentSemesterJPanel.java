    private void MakeCurrentButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_MakeCurrentButtonActionPerformed
        int selectedrow = SemesterTable.getSelectedRow();
        if (selectedrow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a semester first.", "No selection", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String semester = (String) SemesterTable.getValueAt(selectedrow, 0);
        if (semester.equals(business.getCurrentSemester())) {
            JOptionPane.showMessageDialog(this, semester + " is already the current semester.",
                    "Current Semester", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        int choice = JOptionPane.showConfirmDialog(this, "Make " + semester + " the current semester?\n\n"
                + "Faculty and students will see " + semester + "'s course offers as the current ones.",
                "Current Semester", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            business.setCurrentSemester(semester);
        } catch (IllegalArgumentException e) {
            //the schedule list changed since this screen was opened
            JOptionPane.showMessageDialog(this, e.getMessage(), "Current Semester", JOptionPane.ERROR_MESSAGE);
            refresh();
            return;
        }
        refresh();
        JOptionPane.showMessageDialog(this, semester + " is now the current semester.",
                "Current Semester", JOptionPane.INFORMATION_MESSAGE);

    }//GEN-LAST:event_MakeCurrentButtonActionPerformed


