    private void SaveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveButtonActionPerformed
        String first = FirstNameField.getText().trim();
        String last = LastNameField.getText().trim();
        String email = EmailField.getText().trim();
        String phone = PhoneField.getText().trim();

        Person p = faculty.getPerson();
        String error = PersonRules.validate(business.getPersonDirectory(), first, last, email, phone, p);
        if (error != null) {
            JOptionPane.showMessageDialog(this, error, "Save changes", JOptionPane.ERROR_MESSAGE);
            return;
        }

        p.setFirstName(first);
        p.setLastName(last);
        p.setEmail(email);
        p.setPhone(phone);

        JOptionPane.showMessageDialog(this, "Faculty record for " + p.getFullName() + " saved.",
                "Save changes", JOptionPane.INFORMATION_MESSAGE);
        goBack();
    }//GEN-LAST:event_SaveButtonActionPerformed


