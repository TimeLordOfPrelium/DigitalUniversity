    //shows every faculty member whose id, name or email contains the search text (all when empty)
    public void refreshTable() {

        String filter = SearchField.getText().trim().toLowerCase();
        DefaultTableModel model = (DefaultTableModel) FacultyTable.getModel();
        model.setRowCount(0);
        shownfaculty.clear();

        for (FacultyProfile fp : business.getFacultyDirectory().getFacultyList()) {

            Person p = fp.getPerson();
            if (!filter.isEmpty()
                    && !p.getPersonId().toLowerCase().contains(filter)
                    && !p.getFullName().toLowerCase().contains(filter)
                    && !p.getEmail().toLowerCase().contains(filter)) {
                continue;
            }

            Object[] row = new Object[5];
            row[0] = p.getPersonId();
            row[1] = p.getFullName();
            row[2] = p.getEmail();
            row[3] = fp.getAcademicProfile().getFacultyAssignments().size();
            row[4] = countCurrentSemester(fp);

            model.addRow(row);
            shownfaculty.add(fp);
        }
    }

    int countCurrentSemester(FacultyProfile fp) {

        Department department = business.getDepartment();
        String semester = business.getCurrentSemester();
        int count = 0;
        for (FacultyAssignment fa : fp.getAcademicProfile().getFacultyAssignments()) {
            if (semester.equals(department.findSemesterOf(fa.getCourseOffer()))) {
                count++;
            }
        }
        return count;
    }

    //the faculty member in the selected row, or null (after telling the user) when nothing is selected
    FacultyProfile getSelectedFaculty() {

        int selectedrow = FacultyTable.getSelectedRow();
        if (selectedrow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a faculty member first.",
                    "No selection", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        return shownfaculty.get(selectedrow);
    }

