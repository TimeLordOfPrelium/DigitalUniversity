    private void DeleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteButtonActionPerformed
        FacultyProfile fp = getSelectedFaculty();
        if (fp == null) {
            return;
        }

        int courses = fp.getAcademicProfile().getFacultyAssignments().size();
        int choice = JOptionPane.showConfirmDialog(this,
                "Delete the faculty record for " + fp.getPerson().getFullName() + "?\n"
                + "Their " + courses + " course(s) will have no teacher until one is assigned,\n"
                + "their login is removed, and their person record is deleted unless they hold another role.",
                "Delete faculty", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        business.deleteFaculty(fp);
        refreshTable();
    }//GEN-LAST:event_DeleteButtonActionPerformed

