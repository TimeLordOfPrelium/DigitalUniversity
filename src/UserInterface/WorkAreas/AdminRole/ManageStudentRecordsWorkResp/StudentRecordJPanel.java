    void displayRecord() {

        Person p = student.getPerson();
        IdValue.setText(p.getPersonId());
        FirstNameField.setText(p.getFirstName());
        LastNameField.setText(p.getLastName());
        EmailField.setText(p.getEmail());
        PhoneField.setText(p.getPhone());

        info5100.university.example.Persona.StudentProfile ap = student.getAcademicProfile();
        Transcript transcript = ap.getTranscript();

        String semester = business.getCurrentSemester();
        CourseLoad current = ap.getCourseLoadBySemester(semester);
        int currentclasses = current == null ? 0 : current.getSeatAssignments().size();
        SummaryLabel.setText("Credits: " + transcript.getTotalCreditHours()
                + "     GPA: " + String.format("%.2f", transcript.getGPA())
                + "     Current semester (" + semester + "): " + currentclasses + " class(es)");

        //transcript rows, oldest semester first
        DefaultTableModel model = (DefaultTableModel) TranscriptTable.getModel();
        model.setRowCount(0);
        ArrayList<CourseLoad> loads = new ArrayList<>(transcript.getCourseLoads());
        loads.sort(Comparator.comparing(CourseLoad::getSemester));
        for (CourseLoad cl : loads) {
            for (SeatAssignment sa : cl.getSeatAssignments()) {
                Object[] row = new Object[4];
                row[0] = cl.getSemester();
                row[1] = sa.getAssociatedCourse();
                row[2] = sa.getCreditHours();
                row[3] = gradeText(sa.getGrade());
                model.addRow(row);
            }
        }
    }

    //grade points shown with their letter, e.g. "A- (3.7)"; 0 means not graded yet
    static String gradeText(float grade) {

        if (grade <= 0) {
            return "In progress";
        }
        String[] letters = {"A", "A-", "B+", "B", "B-", "C+", "C", "C-", "D"};
        float[] points = {4.0f, 3.7f, 3.3f, 3.0f, 2.7f, 2.3f, 2.0f, 1.7f, 1.0f};
        for (int i = 0; i < points.length; i++) {
            if (grade >= points[i] - 0.05f) {
                return letters[i] + String.format(" (%.1f)", grade);
            }
        }
        return String.format("F (%.1f)", grade);
    }

