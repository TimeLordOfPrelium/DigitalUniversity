    private void DeleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteButtonActionPerformed
        StudentProfile sp = getSelectedStudent();
        if (sp == null) {
            return;
        }

        int choice = JOptionPane.showConfirmDialog(this,
                "Delete the student record for " + sp.getPerson().getFullName() + "?\n"
                + "Their classes are dropped (freeing the seats), their login is removed,\n"
                + "and their person record is deleted unless they hold another role.",
                "Delete student", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        business.deleteStudent(sp);
        refreshTable();
    }//GEN-LAST:event_DeleteButtonActionPerformed

