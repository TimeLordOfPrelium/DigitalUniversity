    //shows every student whose id, name or email contains the search text (all when empty)
    public void refreshTable() {

        String filter = SearchField.getText().trim().toLowerCase();
        DefaultTableModel model = (DefaultTableModel) StudentTable.getModel();
        model.setRowCount(0);
        shownstudents.clear();

        for (StudentProfile sp : business.getStudentDirectory().getStudentList()) {

            Person p = sp.getPerson();
            if (!filter.isEmpty()
                    && !p.getPersonId().toLowerCase().contains(filter)
                    && !p.getFullName().toLowerCase().contains(filter)
                    && !p.getEmail().toLowerCase().contains(filter)) {
                continue;
            }

            Transcript transcript = sp.getAcademicProfile().getTranscript();
            Object[] row = new Object[6];
            row[0] = p.getPersonId();
            row[1] = p.getFullName();
            row[2] = p.getEmail();
            row[3] = transcript.getCourseList().size();
            row[4] = transcript.getTotalCreditHours();
            row[5] = String.format("%.2f", transcript.getGPA());

            model.addRow(row);
            shownstudents.add(sp);
        }
    }

    //the student in the selected row, or null (after telling the user) when nothing is selected
    StudentProfile getSelectedStudent() {

        int selectedrow = StudentTable.getSelectedRow();
        if (selectedrow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a student first.",
                    "No selection", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        return shownstudents.get(selectedrow);
    }

