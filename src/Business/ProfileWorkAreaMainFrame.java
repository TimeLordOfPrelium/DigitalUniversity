    private void LoginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LoginButtonActionPerformed
        String un = UserNameTextField.getText().trim();
        String pw = new String(PasswordTextField.getPassword());

        if (un.isEmpty() || pw.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your user name and password.",
                    "Login", JOptionPane.WARNING_MESSAGE);
            return;
        }

        UserAccountDirectory uad = business.getUserAccountDirectory();
        UserAccount useraccount = uad.AuthenticateUser(un, pw);
        if (useraccount == null) {
            //only say "disabled" when the password was right, so we do not leak which accounts exist
            UserAccount match = uad.findUserAccountByUsername(un);
            String message = "Invalid user name or password.";
            if (match != null && match.IsValidUser(un, pw) && !match.isActive()) {
                message = "This account is disabled. Please contact a University Admin.";
            }
            JOptionPane.showMessageDialog(this, message, "Login failed", JOptionPane.ERROR_MESSAGE);
            PasswordTextField.setText("");
            return;
        }

        JPanel workarea = createWorkArea(useraccount);
        if (workarea == null) {
            JOptionPane.showMessageDialog(this, "No work area is set up for the role " + useraccount.getRole() + ".",
                    "Login failed", JOptionPane.ERROR_MESSAGE);
            return;
        }

        useraccount.recordLogin();
        currentuser = useraccount;
        setLoggedIn(true);
        CardSequencePanel.removeAll();
        CardSequencePanel.add("workarea", workarea);
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);
        CardSequencePanel.revalidate();
        CardSequencePanel.repaint();

    }//GEN-LAST:event_LoginButtonActionPerformed

    //routes each role to its own work area; null when the role has none
    private JPanel createWorkArea(UserAccount useraccount) {

        Profile profile = useraccount.getAssociatedPersonProfile();

        if (profile instanceof EmployeeProfile) {
            return new AdminRoleWorkAreaJPanel(business, useraccount, CardSequencePanel);
        }
        if (profile instanceof FacultyProfile) {
            return new FacultyWorkAreaJPanel(business, useraccount, CardSequencePanel);
        }
        if (profile instanceof StudentProfile) {
            return new StudentWorkAreaJPanel(business, useraccount, CardSequencePanel);
        }
        return null;
    }

    private void LogoutButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LogoutButtonActionPerformed
        //drop every open screen and go back to the welcome card
        currentuser = null;
        CardSequencePanel.removeAll();
        CardSequencePanel.add(jLabel3, "card2");
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).show(CardSequencePanel, "card2");
        CardSequencePanel.revalidate();
        CardSequencePanel.repaint();

        setLoggedIn(false);
        UserNameTextField.setText("");
        PasswordTextField.setText("");
        UserNameTextField.requestFocusInWindow();
    }//GEN-LAST:event_LogoutButtonActionPerformed

    //while someone is logged in the login fields are locked and only Logout is available
    private void setLoggedIn(boolean loggedin) {

        UserNameTextField.setEnabled(!loggedin);
        PasswordTextField.setEnabled(!loggedin);
        jButton1.setEnabled(!loggedin);
        LogoutButton.setEnabled(loggedin);

        if (loggedin) {
            SignedInLabel.setText("<html>Signed in as<br>" + currentuser.getAssociatedPersonProfile().getPerson().getFullName()
                    + " (" + currentuser.getRole() + ")</html>");
        } else {
            SignedInLabel.setText("");
        }
    }

